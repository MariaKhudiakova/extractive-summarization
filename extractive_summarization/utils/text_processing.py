class TextProcessor:
    """A class used to split Russian text into sentences and tokens."""

    def split_sentences(self, text: str) -> t.List[str]:
        """
        Split text into sentences preserving their original order.

        :param text: input text
        :return: list of sentences
        """
        if not text:
            return []
        raw = _SENTENCE_SPLIT_RE.split(text.strip())
        return [s.strip() for s in raw if s.strip()]

    def tokenize(self, text: str) -> t.List[str]:
        """
        Tokenize text into lowercase word tokens (Cyrillic + Latin).

        :param text: input text
        :return: list of lowercase word tokens
        """
        return [m.group(0).lower() for m in _WORD_RE.finditer(text)]

    def content_tokens(self, text: str) -> t.List[str]:
        """
        Tokenize text and drop Russian stopwords.

        :param text: input text
        :return: list of content tokens
        """
        return [tok for tok in self.tokenize(text) if tok not in STOPWORDS]
